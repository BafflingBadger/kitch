-- Ingredient image keywords, shared by iOS, the web app and `import-recipe`.
--
-- Each ingredient line stores one keyword (ingredients.keyword). This table is
-- the list those keywords come from:
--
--   keyword     the value stored on ingredients.keyword, and what the AI picks on import
--   image_name  the image to show; several keywords can share one
--               (on iOS, the asset name in Assets.xcassets/Ingredient Icons)
--   aliases     other names for the keyword, used to match typed ingredient lines
--               on the client without AI ("scallion" -> green onion)
--
-- Seeded from the lists hard-coded in the iOS app (Recipe.ingredientImages and
-- IngredientKeywords.aliases), which match import-recipe/ingredient-keywords.ts
-- apart from its "null" sentinel. The typo "chocoloate" stays because stored
-- ingredients use it.
--
-- Reference data: anyone can read it, no client can write it. Change it with a
-- migration. iOS bundles its images, so a new image_name shows as "unknown"
-- until an iOS build with that image ships; point a new keyword at an existing
-- image_name until then.

create table public.ingredient_keywords (
  keyword    text primary key
             check (keyword = lower(btrim(keyword)) and char_length(keyword) between 1 and 60),
  image_name text not null check (char_length(image_name) between 1 and 60),
  aliases    text[] not null default '{}',
  updated_at timestamptz not null default now()
);

alter table public.ingredient_keywords enable row level security;

create policy "Anyone can read ingredient keywords"
  on public.ingredient_keywords for select to anon, authenticated
  using (true);

revoke insert, update, delete, truncate on public.ingredient_keywords from anon, authenticated;

